/**
 * Duplicate product merge gateway (FEATURE_2609_69 / B · FEATURE_2611_09).
 *
 * One to one with the backend `MergeProductsRequest` / `MergeProductsResponse` / `MergePreviewRequest` /
 * `MergePreviewResponse`.
 *
 * 🔴 **Not an automatic merge.** Of the fields and the history, only the values a person picked (`fields`) and
 * the history a person ticked (`transfer`) move to the kept product; the discarded one is soft-deleted. One transaction — a failure changes
 * **nothing**.
 * 🔁 **Master links move with every merge** (FEATURE_2611_09 / D1 — no checkbox, D2). A master whose components
 * would equal another master's is deleted and its listings move to that master; `masterOptionChoices` says
 * where each of its options goes (D18 · D23 · D24). The server refuses a master holding both products with 409
 * (D4) and a missing or foreign choice with 400 (D28).
 */
export interface MergeTransferOptions {
  purchaseRecords: boolean;
  stockMovements: boolean;
  shipmentItems: boolean;
  images: boolean;
  shoppingListItems: boolean;
  priceChangeLogs: boolean;
  /** 옮긴 내용을 남길 물품 설명 끝에 한 줄로 남긴다 */
  appendMemo: boolean;
}

/**
 * 남길 물품에 덮어쓸 값. 🔴 **null 은 「남길 물품의 값을 그대로 둔다」는 뜻**이다 —
 * 버릴 쪽 값이 저절로 섞여 들어오지 않는다.
 */
export interface MergedProductFields {
  productName: string | null;
  brand: string | null;
  barcodeId: string | null;
  price: number | null;
  description: string | null;
  netContent: string | null;
  netContentUnit: string | null;
  /** 개수·개수 단위 — 고르는 항목이다. 🔴 구매처는 여기 없다: 고르지 않고 두 물품 것을 합친다(FEATURE_2609_76 / D16). */
  countQuantity: number | null;
  countUnit: string | null;
  packageHeight: string | null;
  packageLength: string | null;
  packageWidth: string | null;
  /**
   * 대표 사진. 🔴 플래그 컬럼이 아니라 **갤러리 맨 앞 한 장**이라는 뜻이다(PLAN D13).
   * 🔴 `transfer.images` 가 꺼진 채 **버릴 쪽** 사진을 지정하면 서버가 400 을 낸다
   * (그 사진은 이관되지 않아 버릴 물품과 함께 묻히기 때문).
   */
  representativeImageId: number | null;
}

/**
 * Where one option of a deleted master goes (FEATURE_2611_09 / D23 · D24). Exactly one of the two is set:
 * `targetOptionId` = an option of the surviving master, or `newOptionName` = create an option of that name with
 * the deleted option's quantities.
 */
export interface MasterOptionChoice {
  sourceOptionId: number;
  targetOptionId: number | null;
  newOptionName: string | null;
}

export interface MergeProductsRequest {
  /** 살아남는 물품 */
  targetProductId: number;
  /** soft delete 되는 물품 */
  sourceProductId: number;
  fields: MergedProductFields;
  transfer: MergeTransferOptions;
  /** One entry per option row of every preview pair (FEATURE_2611_09 / D28); empty when there is no pair. */
  masterOptionChoices: MasterOptionChoice[];
}

export interface MergeProductsResponse {
  targetProductId: number;
  /**
   * Rows moved per table — keyed by the `MergeTransferOptions` field names, plus `masterProducts` = masters the
   * discarded product was in (FEATURE_2611_09 / D11)
   */
  moved: Record<string, number>;
  /** 옮기지 못해 버린 건수 (`shoppingListItems` 충돌 · `boxRecipes`) */
  droppedOnConflict: Record<string, number>;
  /** 🔴 병합 전 스냅샷 파일 **이름**. 화면에 쓰지 않는다 */
  snapshotFileName: string | null;
  /** Masters whose components changed or that received listings — regenerated by the server; not shown. */
  changedMasterIds: number[];
}

export interface MergePreviewRequest {
  targetProductId: number;
  sourceProductId: number;
}

/** One (product, quantity) of an option, ascending by product id. */
export interface MergePreviewItem {
  productId: number;
  productName: string;
  quantity: number;
}

export interface MergePreviewOption {
  optionId: number;
  name: string;
  items: MergePreviewItem[];
}

/** One option of the deleted master (FEATURE_2611_09 / D23). */
export interface MergePreviewOptionRow {
  sourceOptionId: number;
  sourceOptionName: string;
  /** Its quantities with the discarded product already replaced by the kept one (D24 ④). */
  items: MergePreviewItem[];
  /**
   * First choice (D24 ②). `null` = no surviving option has the same quantities → the first choice is
   * 「새 옵션 만들기」, and only then may it be chosen (D24 ③).
   */
  defaultOptionId: number | null;
}

export interface MergePreviewListing {
  listingId: number;
  listingName: string;
  platform: string;
}

/** A master the merge deletes and the master its listings move to (FEATURE_2611_09 / D16 · D20). */
export interface MergePreviewPair {
  deleteMasterId: number;
  deleteMasterName: string;
  keepMasterId: number;
  keepMasterName: string;
  listings: MergePreviewListing[];
  /** Every option of the surviving master — the choices of each row (D24 ①). */
  keepOptions: MergePreviewOption[];
  optionRows: MergePreviewOptionRow[];
}

/** What the merge does to the masters (FEATURE_2611_09 / D28). Empty `pairs` = no master is deleted. */
export interface MergePreviewResponse {
  pairs: MergePreviewPair[];
}

export interface ProductMergeRepository {
  merge(request: MergeProductsRequest): Promise<MergeProductsResponse>;
  /** Read-only. 409 = a master holds both products (D4) or would equal two masters (D27). */
  preview(request: MergePreviewRequest): Promise<MergePreviewResponse>;
}
